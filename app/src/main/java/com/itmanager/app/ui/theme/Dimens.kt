package com.itmanager.app.ui.theme

import androidx.compose.ui.unit.dp

/**
 * The few sizes every screen shares, so cards and lists line up from tab to tab: the gutter of a screen, the gap
 * between cards, and the padding inside one. New screens use these instead of their own numbers.
 */
object Dimens {
    val Gutter = 16.dp
    val CardGap = 12.dp
    val RowGap = 8.dp
    val CardPadding = 16.dp
    val CardCorner = 16.dp
}
